def role_of(style):
    """장수 성향(병기·책략·방어·치유·보조·문무) → 장비 역할."""
    s = style or ""
    if "병기" in s: return "병기딜러"
    if "책략" in s: return "책략딜러"
    if "문무" in s and "보조" not in s: return "병기딜러"
    if "방어" in s: return "탱커"
    return "서포터"


def recommend(style, tac_types):
    """장수 성향과 그 장수가 쓰는 전법 종류(액티브·추격 등)로 추천 특기 1개 + 이펙트 2개. → {role, trait, alt, effects}"""
    r = role_of(style); t = list(tac_types or [])
    act, pur = any("액티브" in x for x in t), any("추격" in x for x in t)
    if r == "병기딜러": trait, alt, ef = "무외", "신위", ["연마", "결단" if act else "궁지" if pur else "단홍"]
